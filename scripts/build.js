#!/usr/bin/env node
// Builds the static site into dist/.
//
// Pages in this repo are written in Claude artifact format: they start with
// <title>, <meta>, <link> and <style> and leave out the document skeleton,
// which the artifact viewer adds when it publishes. A plain web host does not
// add it, so this script wraps each page in a full HTML document (doctype,
// charset, viewport and the same small reset the viewer uses) and copies
// every other file as is.
//
// It also makes the site an installable app: a web manifest, icons from
// site/icons, and a service worker (sw.js) that keeps the games working
// offline. These are only added to the hosted build, not to the artifacts.
//
// Usage: node scripts/build.js

const fs = require('fs');
const crypto = require('crypto');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const DIST = path.join(ROOT, 'dist');
const SOURCES = ['index.html', 'coin-crawl', 'orbit-hop'];

const RESET = ':root{color-scheme:light;padding-top:env(safe-area-inset-top,0px);padding-bottom:env(safe-area-inset-bottom,0px)}' +
  'body{margin:0;font:14px system-ui,-apple-system,"Segoe UI",Roboto,sans-serif}img{max-width:100%}[hidden]{display:none!important}';

const APP_HEAD = up => `<link rel="manifest" href="${up}manifest.webmanifest">\n<meta name="theme-color" content="#16131d">\n` +
  `<link rel="icon" type="image/png" href="${up}icons/favicon-32.png">\n<link rel="apple-touch-icon" href="${up}icons/apple-touch-icon.png">\n` +
  `<script src="${up}config.js"></script>\n<script src="${up}leaderboard.js"></script>`;
const APP_BODY = up => `<script>if ('serviceWorker' in navigator && location.protocol.startsWith('http')) navigator.serviceWorker.register('${up}sw.js').catch(() => {});</script>`;

// Pull the leading <title>, <meta> and <link> tags into <head>; leave the rest in <body>.
function wrap(html, up) {
  if (/^\s*<!doctype/i.test(html)) return html; // already a full document
  const head = [];
  let rest = html;
  const tag = /^\s*(<title>[\s\S]*?<\/title>|<meta\b[^>]*>|<link\b[^>]*>)/i;
  let m;
  while ((m = rest.match(tag))) { head.push(m[1]); rest = rest.slice(m[0].length); }
  return '<!doctype html>\n<html lang="en">\n<head>\n<meta charset="utf-8">\n' +
    '<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">\n' +
    head.join('\n') + '\n' + APP_HEAD(up) + '\n<style>' + RESET + '</style>\n</head>\n<body>\n' + rest.trim() + '\n' + APP_BODY(up) + '\n</body>\n</html>\n';
}

function copy(rel, srcRoot = ROOT) {
  const src = path.join(srcRoot, rel), dst = path.join(DIST, rel);
  const stat = fs.statSync(src);
  if (stat.isDirectory()) { for (const f of fs.readdirSync(src)) copy(path.join(rel, f), srcRoot); return; }
  fs.mkdirSync(path.dirname(dst), { recursive: true });
  if (rel.endsWith('.html')) fs.writeFileSync(dst, wrap(fs.readFileSync(src, 'utf8'), '../'.repeat(rel.split(path.sep).length - 1)));
  else fs.copyFileSync(src, dst);
}

fs.rmSync(DIST, { recursive: true, force: true });
for (const s of SOURCES) copy(s);
copy('icons', path.join(ROOT, 'site'));
copy('config.js', path.join(ROOT, 'site'));
copy('leaderboard.js', path.join(ROOT, 'site'));
fs.writeFileSync(path.join(DIST, '.nojekyll'), '');

fs.writeFileSync(path.join(DIST, 'manifest.webmanifest'), JSON.stringify({
  name: 'Coin Crawl', short_name: 'Coin Crawl', description: 'An idle dungeon crawler, plus Orbit Hop.',
  start_url: './coin-crawl/', scope: './', display: 'standalone', orientation: 'any',
  background_color: '#16131d', theme_color: '#16131d',
  icons: [{ src: 'icons/icon-192.png', sizes: '192x192', type: 'image/png' }, { src: 'icons/icon-512.png', sizes: '512x512', type: 'image/png' }, { src: 'icons/icon-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' }]
}, null, 2));

// Service worker: precaches every built file; pages and scripts are fetched
// fresh when online (so updates show up) and served from cache offline.
const files = [];
(function list(dir, rel) { for (const d of fs.readdirSync(dir, { withFileTypes: true })) { const r = rel ? rel + '/' + d.name : d.name; if (d.isDirectory()) list(path.join(dir, d.name), r); else if (d.name !== '.nojekyll') files.push(r); } })(DIST, '');
const hash = crypto.createHash('sha1');
for (const f of files.sort()) hash.update(f).update(fs.readFileSync(path.join(DIST, f)));
const precache = ['./', ...files.map(f => f.endsWith('index.html') ? './' + f.slice(0, -'index.html'.length) : './' + f)];
fs.writeFileSync(path.join(DIST, 'sw.js'), `// Generated by scripts/build.js
const CACHE = 'idk-${hash.digest('hex').slice(0, 12)}';
const PRECACHE = ${JSON.stringify([...new Set(precache)])};
self.addEventListener('install', e => { e.waitUntil(caches.open(CACHE).then(c => c.addAll(PRECACHE)).then(() => self.skipWaiting())); });
self.addEventListener('activate', e => { e.waitUntil(caches.keys().then(ks => Promise.all(ks.filter(k => k.startsWith('idk-') && k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim())); });
self.addEventListener('fetch', e => {
  const req = e.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin === location.origin) {
    // network first, so a new version shows up right away; cache when offline
    e.respondWith(fetch(req).then(res => { if (res.ok) { const copy = res.clone(); caches.open(CACHE).then(c => c.put(req, copy)); } return res; }).catch(() => caches.match(req, { ignoreSearch: true }).then(r => r || caches.match('./'))));
  } else if (/fonts\.(googleapis|gstatic)\.com$/.test(url.hostname)) {
    // fonts: cache first
    e.respondWith(caches.match(req).then(r => r || fetch(req).then(res => { const copy = res.clone(); caches.open(CACHE).then(c => c.put(req, copy)); return res; })));
  }
});
`);
const count = (dir) => fs.readdirSync(dir, { withFileTypes: true }).reduce((n, d) => n + (d.isDirectory() ? count(path.join(dir, d.name)) : 1), 0);
console.log(`Built ${count(DIST)} files into dist/`);
